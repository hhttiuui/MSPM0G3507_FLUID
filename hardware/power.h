/*
 * power.h —— 一键开关机的「电源保持」信号（PWR_HOLD = PA22）
 *
 * ---------------------------------------------------------------------------
 * 接线图 ①：实际电路（按你口述整理）
 * ---------------------------------------------------------------------------
 *   · VBAT ──[51k]──► PMOS#1 的 G（主栅极节点）
 *   · PMOS#1：S→VBAT，D→VDD（给 MCU 供电），G = 主栅极节点
 *   · PMOS#2：**同一型号（AO3415A，P 沟道）**，D 接主栅极节点，S→GND，
 *             G 经 1k 接 PA22
 *   · 按键网络：D1 阳极→主栅极，D2 阳极→USER1(PA25)，两管阴极并在一起接按键，
 *             按键另一端接 GND
 *
 *                      VBAT (4.2V)
 *                        │
 *      ┌─────────────────┴──────────────┐
 *      │                                │
 *    [51k]                    S ┌───────┴─────┐
 *      │                        │   PMOS#1    │
 *      │                        │   AO3415A   │──► D ──► VDD ──► MCU 供电
 *      │                        └──────┬──────┘
 *      │                               │ G
 *  ────┴───────────────────────────────┴───────────────── 主栅极节点
 *      │                               │
 *      │                        D ┌────┴───────┐
 *      ├──────────────────────────┤   PMOS#2   │   ⚠ 同一型号（P 沟道！）
 *      │                          │   AO3415A  │
 *      │                          │ S          │────► GND
 *      │                          └─────┬──────┘
 *      │                                │ G
 *      │                                └──[ 1k ]──► PA22（MCU，推挽 3.3V/0V）
 *      │
 *   ┌──┴──────────── 按键网络（独立画） ─────────────────────────────┐
 *   │   主栅极节点 ──►|D1───┬───[ 按键 ]──► GND                     │
 *   │   USER1(PA25) ─►|D2───┘                                       │
 *   │   （►| 表示阳极在左、阴极在右；两管阴极并为"按键节点"）        │
 *   │   按下按键：主栅极被 D1 拉到 ~0.6V，同时 PA25 被 D2 拉到 ~0.7V │
 *   │   松开    ：按键节点悬空，PA25 靠内部上拉读高                  │
 *   └────────────────────────────────────────────────────────────────┘
 *
 *   ⚠ 这颗 D1/D2 网络设计是对的、而且很巧：D1 既让按键能把主栅极拉低，
 *     又**挡住 4.2V 反灌进 PA25**（否则 PMOS#1 关断时主栅极 4.2V 会顶到
 *     MCU 引脚上，超过 I/O 耐压）。这部分不用改。
 *
 * ---------------------------------------------------------------------------
 * ❌ 根因：PMOS#2 型号用错了 —— P 沟道管**不能**当"低边开关"去拉低栅极
 * ---------------------------------------------------------------------------
 *   (1) 它永远不会导通。PMOS 要导通必须 Vgs < 0，即栅极电位**低于源极**。
 *       你把 S 接地（0V）、G 由 PA22 驱动（只有 0V / 3.3V）
 *       ⇒ Vgs 恒 ≥ 0 ⇒ 沟道永远关着，**PA22 对它完全不起作用**。
 *
 *   (2) 更要命的是它的**体二极管方向是 D→S**（阳极在漏极，阴极在源极/衬底）。
 *       你 D 接主栅极、S 接地 ⇒ 这颗管子的体二极管就是一根
 *       "主栅极 → 地"的正向二极管，只要主栅极高于 ~0.6V 就导通。
 *
 *   (3) 于是主栅极被这个体二极管**钳住**：
 *         51k 从 4.2V 灌进去  (4.2 − 0.5)/51k ≈ 72µA
 *         体二极管在这点电流下压降 0.5~0.7V
 *         ⇒ 主栅极 ≈ 0.5V   ← **这就是你量到的 0.5V，且与 PA22 输出无关**
 *
 *   后果：PMOS#1 的 Vgs = 0.5 − 4.2 = **−3.7V，永久全导通**
 *         ⇒ 系统始终通着电、PA22 完全不起作用、**永远关不了机**、电池一直耗。
 *
 *   ✔ 30 秒验证我的判断（任选其一）：
 *     · 万用表二极管档：红笔接 PMOS#2 的 D、黑笔接 S → 应读到 ~0.5~0.6V 的
 *       二极管压降。这条通路存在，就说明主栅极被它钳住了。
 *     · 把 PMOS#2 的 D 断开（或拆掉这颗管）→ 主栅极应立刻升到 4.2V。
 *
 * ---------------------------------------------------------------------------
 * ✅ 修法：把 PMOS#2 换成 **N 沟道**器件。拓扑、二极管、代码都不用动！
 * ---------------------------------------------------------------------------
 *   · NMOS（2N7002 / AO3400）：S→GND，D→主栅极，G 经 1k 接 PA22
 *   · NPN （S8050 / MMBT3904）：E→GND，C→主栅极，B 经 1k 接 PA22
 *                              （基极加 10k 下拉到 GND，防止 MCU 未上电时误导通）
 *
 *   为什么换上就能工作：
 *     PA22 高(3.3V) → N 管 Vgs=+3.3V → 导通 → 主栅极被拉到 ~0.05V
 *                   → PMOS#1 的 Vgs ≈ −4.15V → 全导通 → 自锁 ✓
 *     PA22 低(0V)   → N 管关断 → 51k 把主栅极拉回 4.2V
 *                   → PMOS#1 的 Vgs = 0 → 关断 → 断电 ✓
 *
 *   为什么 NMOS 不会像 PMOS 那样钳位：NMOS 的体二极管方向是 **S→D**
 *   （阳极在源极/衬底），也就是"地 → 主栅极"；主栅极为正电压时它是**反偏**，
 *   不导通，所以不会把节点钳在 0.6V ✓
 *
 *   ⇒ Power_Hold() = PA22 高、Power_Release() = PA22 低，
 *     **和现在的代码完全一致，一行都不用改。**
 *
 * ---------------------------------------------------------------------------
 * 接线图 ②：改好之后的完整接线
 * ---------------------------------------------------------------------------
 *                      VBAT (4.2V)
 *                        │
 *      ┌─────────────────┴──────────────┐
 *      │                                │
 *    [10k]                    S ┌───────┴─────┐
 *      │                        │   PMOS#1    │
 *      │                        │   AO3415A   │──► D ──► VDD ──► MCU 供电
 *      │                        └──────┬──────┘
 *      │                               │ G
 *  ────┴───────────────────────────────┴───────────────── 主栅极节点
 *      │                               │
 *      │                               ├──[ 1~4.7µF ]──► GND
 *      │                               │        保持电容 τ=R×C 要 >10ms
 *      │                        D ┌────┴───────┐
 *      ├──────────────────────────┤   NMOS     │   ← ★ 只换这一颗
 *      │                          │ (2N7002)   │
 *      │                          │ S          │────► GND
 *      │                          └─────┬──────┘
 *      │                                │ G
 *      │                                └──[ 1k ]──► PA22
 *      │
 *   按键网络保持不变（D1/D2 + 按键）
 *
 *   元件取值提醒（AO3415A 的 VGS(th) 最低只有 −0.3V，主栅极节点宁"硬"勿"软"）：
 *     · 51k → 建议 **10k~22k**：51k 时只要 6µA 漏电就能把压降顶到 0.3V
 *       （刚好是 AO3415A 的最坏阈值 → 关不严）
 *     · 保持电容用 **MLCC**（别用电解/钽，自身漏电就是那条漏电流）
 *     · D1/D2 用肖特基（如 BAT54 / 1N5819）比硅管好：压降更低，主栅极能被
 *       拉得更低，PMOS#1 开得更透
 *
 * ---------------------------------------------------------------------------
 * 为什么不需要在 main() 里写代码
 * ---------------------------------------------------------------------------
 * SysConfig 里 PIN_PWR_HOLD 的 initialValue = SET，
 * 生成的 SYSCFG_DL_GPIO_init() 是「先 setPins 再 enableOutput」，
 * 所以引脚使能成输出的那一刻就已经是高电平，天然完成自锁。
 * 而 SYSCFG_DL_GPIO_init() 又是 SYSCFG_DL_init() 的第二步，上电后极早执行。
 *
 * ⚠️ 硬件上必须在 PMOS 栅极对地加一个电容（或用 RC 延时），
 *    否则按键松手太快时 MCU 还没跑到 GPIO 初始化就会掉电。
 *    电容值大致按「松手后还能维持 > 10 ms」估算（τ = R×C）。
 *
 * ---------------------------------------------------------------------------
 * 一键开关机：PWR_HOLD 之外还要读 USER1
 * ---------------------------------------------------------------------------
 *   USER1(PA25)：按下 = 低，松开 = 高（上拉 + 按键接地）。
 *
 *   开机：按键按下 → 硬件给电 → MCU 上电 → 上面的 GPIO 初始化自动完成自锁。
 *         ⚠ 此刻按键**还按着**，USER1 读到的是低 —— 绝不能当成"要关机"，
 *           必须等它松开过一次之后才允许关机（这是最容易踩的坑：
 *           不处理的话一上电就被判定成"按下" → 立刻关机 → 永远开不了机）。
 *   关机：进入就绪状态后，**持续按住 2 秒**才关机（防误触），中途松手取消。
 *         "关机" = Power_Release()，之后松手由硬件断电。
 *
 * 实现在 power.c：由 TIMA0 的 5ms 中断每拍调一次 PowerKey_Task()，
 * 状态机只通过 Key_IsDown(KEY_USER1) 读按键（去抖已经在 key.c 里做完了）。
 * 放中断里而不是主循环，是为了主循环卡死时仍能关机 —— 否则 PA22 永远放不掉、
 * 用户只能拔电池。
 */
#ifndef POWER_H
#define POWER_H

#include "ti_msp_dl_config.h"

/* 关机：释放保持信号，硬件随即断电 */
static inline void Power_Release(void)
{
    DL_GPIO_clearPins(GPIO_PWR_PORT, GPIO_PWR_PIN_PWR_HOLD_PIN);
}

/* 保持供电。开机后已经是高电平，一般不需要再调用 */
static inline void Power_Hold(void)
{
    DL_GPIO_setPins(GPIO_PWR_PORT, GPIO_PWR_PIN_PWR_HOLD_PIN);
}

/* ==================== 一键开关机（实现见 power.c） ==================== */

/* 长按多久才关机（防误触）。改这个值不用动别的地方 */
#define POWER_OFF_HOLD_MS       (2000u)

/* 每 KEY_TICK_MS(5ms) 调一次。放 TIMA0 中断里，紧跟 Key_Task() 之后 */
void PowerKey_Task(void);

/* 主循环里调：若已经释放自锁（PA22 已拉低），就停在这里等硬件断电。
 * ⚠ 关机后按键可能还按着、系统靠按键供电，这段时间什么都别做
 *   （尤其别写 flash、别再初始化外设）。 */
void PowerKey_CheckShutdown(void);

#endif /* POWER_H */
