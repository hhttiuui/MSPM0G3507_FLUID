/* 二分查找。找不到返回 0，调用方要判空。 */
static const wqf_glyph_t *WQF_Find(uint32_t cp)
{
    static wqf_glyph_t g;
    uint16_t lo = 0u, hi = WQF_COUNT;

    while (lo < hi) {
        uint16_t mid = (uint16_t) ((lo + hi) >> 1);

        if (s_wqf_cp[mid] == cp) {
            g.cp  = cp;
            g.adv = s_wqf_adv[mid];
            g.bm  = &s_wqf_bm[mid * (WQF_BPR * WQF_H)];
            return &g;
        }
        if (s_wqf_cp[mid] < cp) { lo = (uint16_t) (mid + 1u); }
        else                    { hi = mid; }
    }
    return 0;
}

