#ifndef VCMD_H
#define VCMD_H

#include <stdint.h>

/**
 * @file vcmd.h
 * @brief 串口下行文本命令（UART1 RX + DMA_CH0）
 *
 * 目的：调参、做亮度标定、看运行状态，都不用回 CCS 改内存，直接在串口终端
 * 里敲一行。移植自 MSPM0G3507_DRV8316 工程（那边已验证过）。
 *
 * ==================== 硬件 ====================
 *   UART1  TX = PB6，RX = PB7，**115200** 8N1（CH340N 转 USB）
 *   DMA_CH0  触发源 = DMA_UART1_RX_TRIG，f2b / 字节宽 / 目的自增
 *
 * ==================== 为什么用 DMA 轮询而不是 RX 中断 ====================
 *   1) 不依赖 UART_0_INST_IRQHandler 能否覆盖启动文件里的弱符号
 *   2) 轮询一次只读两个寄存器，没人打字时开销≈0
 *   3) DMA 直接搬到 RAM，不会有 FIFO 溢出丢字节
 *
 * ==================== 为什么不用"两段式 DMA" ====================
 *   `串口与画面功能设计.md` 里为传画面设计过"先收包头拿长度、再收数据"。
 *   这里用不上：**定长缓冲 + 轮询**天然没有"不知道长度"的问题，断线也只是
 *   DMA 干等着，主循环照跑。传画面时同样沿用这套，不需要包头。
 *
 * ==================== 命令格式 ====================
 *   一行一条，以 '\n' 或 '\r' 结尾：
 *
 *   ① 命令号形式（上位机滑块/按钮用，不需要 MCU 侧字符串表）：
 *        267 550        → 命令号 267，arg0 = 550
 *        513 200        → 命令号 513，arg0 = 200
 *
 *   ② 别名形式（手打方便，空格/等号/逗号都当分隔符）：
 *        bc 128        或   bc=128
 *        px 3 5 200
 *
 *   别名表见 vcmd.c 的 s_alias[]，命令号见 debug.h 的 DBG_CMD_*。
 *
 * ⚠ **一次粘贴不要超过 512 字节**（约 15~20 行短命令）。
 *   RX DMA 缓冲是 512 字节，115200 下要 44 ms 才能填满；
 *   超过这个量，DMA 缓冲满了以后的字节会丢（UART FIFO 只有 4 级）。
 *
 * ==================== 二进制帧（上位机直显）====================
 *   行首字节 0xA5 → 按二进制包解析；否则按文本命令。
 *   ⚠️ 只在**行首**识别（见 vcmd.c 里的说明）：0xA5 也是 UTF-8 汉字的
 *      中间字节，整行都找包头会把 `text 你好世界` 截断成乱码。
 *   包格式：0xA5 | ver | flags | rows=16 | cols=15 | len | payload
 *     8bit：len = 240（行优先 idx = row×15+col，值 = 0~255）
 *     1bit：len = 32 （16 行 × 2 字节，bit7 = 该行第 1 个点）
 *   解析后调用 App_ShowDirectFrame()，把画面切到"单帧画面"场景显示。
 *   ⚠ 没有 CRC：单帧直显丢包就重发；以后做 Flash 槽上传时再加。
 *
 * ⚠ **不回显、不应答**。上行是 FireWater 遥测流，混进一行 "OK" 会让
 *   VOFA+ 解析出一帧假数据。命令有没有生效，看 `dbg.cmd.result`、
 *   `dbg.uart.bin_ok` 和对应的观测量。
 */

/* 上电初始化：武装 RX DMA。必须在主循环开始前调用一次。 */
void VCMD_Init(void);

/* 主循环每圈调一次。没有数据时只做两次寄存器读。 */
void VCMD_Tick(void);

/* 最近一次带字符串的命令（目前只有 `text`）的参数。
 *
 * ⚠ 只在**处理那条命令的 cmd() 里**读才有意义 —— 它是"下一条带字符串的命令
 *   会覆盖"的共享缓冲，别在别的地方缓存这个指针。
 * 没收到过就返回空串（不是 NULL）。 */
const char *VCMD_GetString(void);

#endif /* VCMD_H */
